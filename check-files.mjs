import {readFile,writeFile,mkdir} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {createLayout} from './dist/layout.js';
import {buildPDF} from './dist/pdf.js';
import {createResumeFile,readResumeFile,RESUME_ATTACHMENT} from './dist/resume-file.js';
import {PDFDocument} from './dist/assets/pdf-lib.esm.min.js';
const seed=JSON.parse(await readFile(new URL('./fixtures/original-seed.json',import.meta.url),'utf8'));
const metrics=JSON.parse(await readFile(new URL('./dist/assets/fonts/metrics.json',import.meta.url),'utf8'));
const loadFont=async name=>new Uint8Array(await readFile(new URL('./dist/assets/fonts/'+name,import.meta.url)));
const draft=structuredClone(seed);
draft.sections[0].items[0].roles[0].bullets.push({text:'Added an integration test so this bullet survives saving and uploading.'});
draft.layout.spacing=97;
draft.sections[4].enabled=false;
const full=createResumeFile(draft),visible=createResumeFile(draft,{visibleOnly:true});
assert.equal(full.resume.sections.length,5);
assert.equal(visible.resume.sections.length,4);
assert.ok(!JSON.stringify(full).includes('originalLines'));
const json=new File([JSON.stringify(full)],'resume.json',{type:'application/json'});
assert.deepEqual(await readResumeFile(json),full.resume);
assert.deepEqual(await readResumeFile(new File([JSON.stringify(draft)],'legacy.json')),draft);
const bytes=await buildPDF(createLayout(draft,metrics),metrics,loadFont,visible);
const restored=await readResumeFile(new File([bytes],'resume.pdf',{type:'application/pdf'}));
assert.deepEqual(restored,visible.resume);
assert.equal(restored.sections[0].items[0].roles[0].bullets.at(-1).text,draft.sections[0].items[0].roles[0].bullets.at(-1).text);
const edited=structuredClone(restored);
edited.sections[0].items[0].roles[0].bullets.push({text:'A second edit after uploading the first PDF.'});
const second=await buildPDF(createLayout(edited,metrics),metrics,loadFont,createResumeFile(edited,{visibleOnly:true}));
assert.deepEqual(await readResumeFile(new File([second],'second.pdf')),createResumeFile(edited,{visibleOnly:true}).resume);
const compressed=await PDFDocument.create();compressed.addPage();await compressed.attach(new TextEncoder().encode(JSON.stringify(full)),RESUME_ATTACHMENT,{mimeType:'application/json'});
assert.deepEqual(await readResumeFile(new File([await compressed.save()],'compressed.pdf')),full.resume);
const original=await readFile(new URL('./dist/assets/original.pdf',import.meta.url));
await assert.rejects(readResumeFile(new File([original],'old.pdf')),/no editable Resume Studio data/);
await assert.rejects(readResumeFile(new File(['bad json'],'broken.json')),/readable resume data/);
await assert.rejects(readResumeFile(new File([JSON.stringify({...full,schemaVersion:99})],'future.json')),/cannot open/);
const dest='./tmp/qa';await mkdir(dest,{recursive:true});
await writeFile(dest+'/portable-resume.pdf',bytes);await writeFile(dest+'/portable-resume.json',JSON.stringify(full,null,2));
console.log('Portable files verified: PDF and JSON round trips, repeated edits, compressed PDF attachments, hidden sections, legacy backups and invalid files.');
